// Helper to get all lessons belonging to a specific unit
export function getLessonsByUnit(unitId) {
  return TYPING_LESSONS.filter((l) => l.unitId === unitId);
}

// Helper to get unit details by unitId
export function getUnitById(unitId) {
  return TYPING_UNITS.find((u) => u.id === unitId) || TYPING_UNITS[0];
}

// Helper to get lesson by ID
export function getLessonById(lessonId) {
  return TYPING_LESSONS.find((l) => l.id === lessonId) || TYPING_LESSONS[0];
}
