export function getShortcutLevelById(levelId) {
  for (const unit of SHORTCUT_CURRICULUM.officeNinja.units) {
    const found = unit.levels.find((lvl) => lvl.id === levelId);
    if (found) return { ...found, mode: "officeNinja", unitId: unit.id, unitName: unit.name };
  }
  for (const unit of SHORTCUT_CURRICULUM.textNavigator.units) {
    const found = unit.levels.find((lvl) => lvl.id === levelId);
    if (found) return { ...found, mode: "textNavigator", unitId: unit.id, unitName: unit.name };
  }
  return null;
}
